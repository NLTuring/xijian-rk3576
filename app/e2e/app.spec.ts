test('actual microphone capture saves pending audio and plays back after reload', async ({
  page,
}) => {
  await page.goto('/')
  await page.getByRole('button', { name: '我的', exact: true }).click()
  await page.getByRole('button', { name: /真实采集/ }).click()
  await page.getByRole('button', { name: '今天', exact: true }).click()
  await expect(page.getByRole('heading', { name: '还没有夜间记录' })).toBeVisible()
  await page.getByRole('button', { name: '准备今晚监测' }).click()
  await page.getByRole('button', { name: '开始前台采集', exact: true }).click()
  await expect(page.getByRole('heading', { name: '安静记录中。' })).toBeVisible()
  await expect(page.locator('.capture-timer strong')).not.toHaveText('00:00:00')
  await page.getByRole('button', { name: '结束记录', exact: true }).click()
  await page.getByRole('button', { name: '确认结束' }).click()
  await expect(page.getByRole('heading', { name: '这段声音，已留存。' })).toBeVisible()
  await page.getByRole('button', { name: '返回今天' }).click()
  await expect(page.getByText('等待分析', { exact: true })).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: '回听采集原声' }).click()
  await expect(page.getByRole('button', { name: '播放声音' })).toBeEnabled()
  await page.getByRole('button', { name: '播放声音' }).click()
  await expect(page.locator('audio')).toHaveJSProperty('paused', false)
  await page.getByRole('button', { name: '删除这段声音' }).click()
  await page.getByRole('button', { name: '确认删除声音' }).click()
  await expect(page.getByRole('button', { name: '播放声音' })).toBeDisabled()
  await page.getByRole('button', { name: '返回', exact: true }).click()
  await expect(page.getByRole('button', { name: '原声已删除' })).toBeDisabled()
})

